'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (cb) => {
  const fn = (_e, ...args) => cb(...args);
  ipcRenderer.on(channel, fn);
  return () => ipcRenderer.removeListener(channel, fn);
};

contextBridge.exposeInMainWorld('fengshui', {
  init: (id) => ipcRenderer.invoke('fengshui:init', id),
  about: () => ipcRenderer.invoke('fengshui:about'),
  openRepo: () => ipcRenderer.send('fengshui:open-repo'),
  onWidget: on('fengshui:widget'),
  onSettings: on('fengshui:settings'),
  onDoc: on('fengshui:doc'),
  onResume: on('fengshui:resume'),
  onMenuAction: on('fengshui:menu-action'),
  onFocusWidget: on('fengshui:focus-widget'),

  updateWidget: (id, patch) => ipcRenderer.send('fengshui:update-widget', id, patch),
  gestureStart: (kind, edge) => ipcRenderer.send('fengshui:gesture-start', kind, edge),
  gestureEnd: () => ipcRenderer.send('fengshui:gesture-end'),
  contextMenu: (extra) => ipcRenderer.send('fengshui:context-menu', extra),
  openSettings: (id) => ipcRenderer.send('fengshui:open-settings', id),
  fengShui: () => ipcRenderer.send('fengshui:feng-shui'),
  onBar: on('fengshui:bar'),
  barSize: (w) => ipcRenderer.send('fengshui:bar-size', w),
  barFocus: () => ipcRenderer.send('fengshui:bar-focus'),
  barKeys: (on) => ipcRenderer.send('fengshui:bar-keys', on),
  barStep: (dir) => ipcRenderer.send('fengshui:bar-step', dir),
  onBarKeys: on('fengshui:bar-keys'),
  openNuke: () => ipcRenderer.send('fengshui:nuke-open'),
  saveLayout: (name) => ipcRenderer.send('fengshui:save-layout', name),
  lockLayout: (on) => ipcRenderer.send('fengshui:lock-layout', !!on),
  copy: (text) => ipcRenderer.send('fengshui:copy', text),
  stopwatch: (action) => ipcRenderer.invoke('fengshui:stopwatch', action),

  addWidget: (type) => ipcRenderer.invoke('fengshui:add-widget', type),
  duplicateWidget: (id) => ipcRenderer.send('fengshui:duplicate-widget', id),
  removeWidget: (id) => ipcRenderer.send('fengshui:remove-widget', id),
  updateSettings: (patch) => ipcRenderer.send('fengshui:update-settings', patch),
  createLayout: (name, fromId) => ipcRenderer.invoke('fengshui:create-layout', name, fromId),
  renameLayout: (id, name) => ipcRenderer.send('fengshui:rename-layout', id, name),
  moveLayout: (id, index) => ipcRenderer.send('fengshui:move-layout', id, index),
  deleteLayout: (id) => ipcRenderer.send('fengshui:delete-layout', id),
  switchLayout: (id) => ipcRenderer.send('fengshui:switch-layout', id),
  savePreset: (name, appearance) => ipcRenderer.invoke('fengshui:save-preset', name, appearance),
  deletePreset: (id) => ipcRenderer.send('fengshui:delete-preset', id),
  pickImage: () => ipcRenderer.invoke('fengshui:pick-image'),
  listApps: (refresh) => ipcRenderer.invoke('fengshui:apps-list', refresh),
  appIcon: (p, size) => ipcRenderer.invoke('fengshui:app-icon', p, size),
  bundleId: (p) => ipcRenderer.invoke('fengshui:bundle-id', p),
  resolveApps: (entries, size) => ipcRenderer.invoke('fengshui:apps-resolve', entries, size),
  launch: (p) => ipcRenderer.invoke('fengshui:launch', p),
  weather: (loc, force) => ipcRenderer.invoke('fengshui:weather', loc, force),
  pizzint: (kind, force) => ipcRenderer.invoke('fengshui:pizzint', kind, force),
  openPizzint: (kind) => ipcRenderer.send('fengshui:pizzint-open', kind),
  searchCities: (q) => ipcRenderer.invoke('fengshui:city-search', q),
  importImage: (p) => ipcRenderer.invoke('fengshui:import-image', p),
  pickPhoto: () => ipcRenderer.invoke('fengshui:pick-photo'),
  pathForFile: (file) => webUtils.getPathForFile(file),
  timeZones: () => ipcRenderer.invoke('fengshui:time-zones'),
  films: (opts) => ipcRenderer.invoke('fengshui:films', opts),
  filmPoster: (url) => ipcRenderer.invoke('fengshui:film-poster', url),
  playFilm: (files) => ipcRenderer.invoke('fengshui:film-play', files),
  openFilmPage: (link) => ipcRenderer.send('fengshui:film-page', link),
  openWatchlist: (user) => ipcRenderer.send('fengshui:open-watchlist', user),
  filmDetails: (slugs) => ipcRenderer.invoke('fengshui:film-details', slugs),
  watched: (user, force) => ipcRenderer.invoke('fengshui:watched', user, force),
  openProfile: (user) => ipcRenderer.send('fengshui:open-profile', user),
  pickModel: () => ipcRenderer.invoke('fengshui:pick-model'),
  pickPage: () => ipcRenderer.invoke('fengshui:pick-page'),
  records: (force) => ipcRenderer.invoke('fengshui:records', force),
  recordsOpen: (url) => ipcRenderer.send('fengshui:records-open', url),
  recordsPlaying: (on, title) => ipcRenderer.send('fengshui:records-playing', on, title),
  onRecordsCmd: on('fengshui:records-cmd'),
  library: (op, ...args) => ipcRenderer.invoke('fengshui:library', op, ...args),
  onLibrary: on('fengshui:library-changed'),
  squeeze: (op, ...args) => ipcRenderer.invoke('fengshui:squeeze', op, ...args),
  onSqueeze: on('fengshui:squeeze-changed'),
  cabinet: (op, ...args) => ipcRenderer.invoke('fengshui:cabinet', op, ...args),
  onCabinetProgress: on('fengshui:cabinet-progress'),
  pickFolder: (current) => ipcRenderer.invoke('fengshui:pick-folder', current),
});
